from contextlib import AbstractContextManager
from pathlib import Path
from typing import BinaryIO, Protocol
from domain.entities.models import UploadedModel

class ModelRepositoryPort(Protocol):
    def upload(self, stream: BinaryIO) -> UploadedModel: ...
    def borrow(self, model_id: str, *, pending: bool = False) -> AbstractContextManager[tuple[UploadedModel, Path]]: ...
    def publish(self, model_id: str) -> None: ...
    def list(self) -> list[UploadedModel]: ...
    def delete(self, model_id: str) -> None: ...

class ModelRuntimePort(Protocol):
    def validate(self, model: UploadedModel, directory: Path) -> None: ...
    def predict(self, model: UploadedModel, directory: Path, dataset) -> list[float]: ...
    def tokenizer(self, directory: Path): ...
