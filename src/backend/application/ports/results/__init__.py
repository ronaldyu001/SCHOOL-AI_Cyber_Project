from typing import Protocol

class ResultRepositoryPort(Protocol):
    def save(self, prediction, dataset, model, directory, context) -> str: ...
    def borrow(self, task, result_id): ...
    def rows(self, directory) -> dict: ...
    def sample(self, directory, index): ...
    def save_analysis(self, directory, payload) -> dict: ...

class EvaluationPort(Protocol):
    def evaluate(self, rows, output_contract) -> dict: ...

class ExplanationPort(Protocol):
    def explain(self, directory, metadata, rows, samples, options) -> dict: ...
